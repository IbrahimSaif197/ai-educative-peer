"""Render the panel's real markup against its real stylesheet, for eyeballing.

`webviewMain.test.ts` proves every element `main.js` binds to exists, but no
test can tell you the popover looks wrong. This lifts the template out of
`getHtml()` verbatim, points it at `media/style.css`, forces the popover open
and paints a plausible signed-in state, so what you open in a browser is the
panel rather than an impression of it.

A paint check only: no CSP, no `main.js`, nothing interactive. Re-run after any
change to `getHtml()`.

    python docs/mockups/make-preview.py
"""
