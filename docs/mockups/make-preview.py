def main() -> int:
    src = SRC.read_text(encoding="utf-8")
    start = src.index("<!DOCTYPE html>")
    html = src[start:src.index("</html>`", start) + len("</html>")]

    html = re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]*>', "", html)
    html = re.sub(r'<script nonce="\$\{nonce\}"[^>]*></script>', "", html)

    missed = [find for find, _ in SUBSTITUTIONS if find not in html]
    for find, repl in SUBSTITUTIONS:
        html = html.replace(find, repl, 1)

    html = html.replace("</head>", VSCODE_STUBS + "</head>", 1)

    OUT.write_text(html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + NOTE, 1), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    if missed:
        # Loud rather than silent: a substitution that stops matching means the
        # markup moved, and the preview is quietly no longer what ships.
        print("MARKUP MOVED — these no longer match getHtml():")
        for m in missed:
            print(f"  {m[:78]}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
