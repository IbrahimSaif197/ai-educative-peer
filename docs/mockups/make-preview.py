# The only things VS Code supplies that a browser cannot, set to the editor's
# defaults. Not cosmetic: `--display` and `--sans` (style.css:74-75) reference
# `var(--vscode-font-family)` with NO fallback, so in a browser the
# substitution is guaranteed-invalid and every `font-family: var(--sans)`
# becomes invalid at computed-value time — the panel silently renders in the
# browser's default face instead of Geist and Bricolage. The size tokens all
# carry `, 13px`, so only the two font stacks are affected.
VSCODE_STUBS = """
<style>
  :root {
    --vscode-font-family: "Segoe WPC", "Segoe UI", system-ui, sans-serif;
    --vscode-font-size: 13px;
    --vscode-editor-font-family: Consolas, "Cascadia Mono", monospace;
  }
</style>
"""

